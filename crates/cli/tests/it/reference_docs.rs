//! `docs/reference/cli/`, one page per top-level command plus `README.md` and
//! `commands.json`, generated from the clap command tree. The test fails when a
//! file is stale or missing, or when the folder holds a page the generator no
//! longer writes; `DEVLANES_BLESS=1` rewrites the files and deletes the leftovers.

use std::path::Path;

use clap::{Arg, Command, CommandFactory};
use devlanes_cli::Cli;

/// The command that rewrites every page.
const REGENERATE: &str =
    "DEVLANES_BLESS=1 cargo nextest run -p devlanes-cli -E 'test(cli_reference_is_current)'";

/// The comment under each page's frontmatter.
const GENERATED: &str = "<!-- Generated from the clap definitions in crates/cli by \
     crates/cli/tests/it/reference_docs.rs. Edit the help text in crates/cli, then run \
     DEVLANES_BLESS=1 cargo nextest run -p devlanes-cli -E 'test(cli_reference_is_current)'. -->\n\n";

#[test]
fn cli_reference_is_current() {
    let mut root = Cli::command();
    root.build();
    let mut pages = vec![("README.md".to_owned(), index(&root))];
    for sub in visible(&root) {
        pages.push((format!("{}.md", sub.get_name()), page(sub)));
    }
    pages.push(("commands.json".to_owned(), commands(&root)));
    check_or_bless(
        &Path::new(env!("CARGO_MANIFEST_DIR")).join("../../docs/reference/cli"),
        &pages,
    );
}

/// Compares every page with the committed one and rejects `.md` files the
/// generator did not write, or under `DEVLANES_BLESS=1` writes the pages and
/// deletes those files.
fn check_or_bless(directory: &Path, pages: &[(String, String)]) {
    let leftovers: Vec<_> = std::fs::read_dir(directory)
        .into_iter()
        .flatten()
        .filter_map(Result::ok)
        .map(|entry| entry.path())
        .filter(|path| path.extension().is_some_and(|extension| extension == "md"))
        .filter(|path| {
            let name = path.file_name().and_then(|name| name.to_str());
            !pages.iter().any(|(page, _)| Some(page.as_str()) == name)
        })
        .collect();
    if std::env::var("DEVLANES_BLESS").as_deref() == Ok("1") {
        std::fs::create_dir_all(directory).expect("create docs/reference/cli");
        for (name, generated) in pages {
            std::fs::write(directory.join(name), generated).expect("write a reference page");
        }
        for path in leftovers {
            std::fs::remove_file(&path).expect("delete a page no command generates");
        }
        return;
    }
    for (name, generated) in pages {
        let path = directory.join(name);
        let committed = std::fs::read_to_string(&path).unwrap_or_default();
        assert!(
            &committed == generated,
            "{} is stale or missing; regenerate every page with {REGENERATE}",
            path.display()
        );
    }
    assert!(
        leftovers.is_empty(),
        "{} is not generated by any command; delete it, or run {REGENERATE}",
        leftovers
            .iter()
            .map(|path| path.display().to_string())
            .collect::<Vec<_>>()
            .join(", ")
    );
}

/// `README.md`: the synopsis, the commands with their summaries, the global
/// options, the root examples and the hidden commands.
fn index(root: &Command) -> String {
    let mut page = frontmatter(
        "CLI reference",
        "Every devlanes command and option, with the help text the command prints.",
    );
    page.push_str(
        "Each page below documents one `devlanes` command and its subcommands, with the same \
         help text that `devlanes <command> --help` prints.\n\n",
    );
    if let Some(about) = root.get_long_about().or(root.get_about()) {
        page.push_str(&paragraphs(&about.to_string()));
    }
    page.push_str(&format!("```text\n{}\n```\n\n", usage(root)));
    page.push_str("## Commands\n\n");
    for sub in visible(root) {
        let about = sub
            .get_about()
            .map(|about| sentence(&escape(&about.to_string())))
            .unwrap_or_default();
        page.push_str(&format!(
            "- [`devlanes {name}`]({name}.md): {about}\n",
            name = sub.get_name()
        ));
    }
    page.push_str(
        "\n## Global options\n\nAccepted by every command, before or after the command name.\n\n",
    );
    for arg in root
        .get_arguments()
        .filter(|arg| shown(arg) && arg.is_global_set())
    {
        page.push_str(&argument(arg, ""));
    }
    if let Some(after) = root.get_after_long_help().or(root.get_after_help()) {
        let after = after.to_string();
        // The root help explains references in a paragraph; the docs have a page for them.
        let examples: Vec<&str> = after
            .trim()
            .split("\n\n")
            .filter(|block| !block.starts_with("References:"))
            .collect();
        page.push_str(&format!(
            "\n## Examples\n\n```text\n{}\n```\n\n",
            examples.join("\n\n")
        ));
    }
    page.push_str(
        "A command names lanes and units with references such as `2`, `feat/checkout` or \
         `acme@2:api`; [lane and unit references](../lane-and-unit-references.md) lists \
         every form.\n",
    );
    page.push_str(
        "\n## Hidden commands\n\nHidden from `--help` because you rarely type them. A \
         `remote.boxes.<name>.command` must end with `devlanes tunnel --stdio` \
         ([Connect to a box through a command](../../how-to/remote/connect-by-command.md)); \
         devlanes, ssh and the install scripts run the others.\n\n",
    );
    let mut found = Vec::new();
    hidden(root, "devlanes", &mut found);
    for (usage, help) in found {
        page.push_str(&format!("- `{usage}`: {}\n", sentence(&escape(&help))));
    }
    page
}

/// The page of one top-level command: its own help, then one section per
/// subcommand.
fn page(command: &Command) -> String {
    let about = command
        .get_about()
        .map(|about| about.to_string())
        .unwrap_or_default();
    let mut page = frontmatter(&format!("devlanes {}", command.get_name()), &about);
    section(&mut page, command, "devlanes", 1);
    page.truncate(page.trim_end().len());
    page.push_str("\n\nEvery command also takes the [global options](README.md#global-options).\n");
    page
}

/// `commands.json`: every command path with its flags and aliases, for the
/// website to check the `$ devlanes ...` lines in the docs. Hidden commands are
/// in it, since pages name some of them; clap's `help` subcommands are not.
fn commands(root: &Command) -> String {
    let mut entries = Vec::new();
    command_entries(root, &mut Vec::new(), &mut entries);
    let mut text = serde_json::to_string_pretty(&serde_json::json!({ "commands": entries }))
        .expect("serialize commands.json");
    text.push('\n');
    text
}

/// The entry of `command` at `path`, then those of its subcommands in clap's
/// order. Global options are listed on every entry, since they are accepted after
/// any command name.
fn command_entries(
    command: &Command,
    path: &mut Vec<String>,
    entries: &mut Vec<serde_json::Value>,
) {
    let mut flags: Vec<String> = command
        .get_arguments()
        .flat_map(|arg| {
            let longs = arg
                .get_long()
                .into_iter()
                .chain(arg.get_all_aliases().unwrap_or_default())
                .map(|long| format!("--{long}"));
            let shorts = arg
                .get_short()
                .into_iter()
                .chain(arg.get_all_short_aliases().unwrap_or_default())
                .map(|short| format!("-{short}"));
            longs.chain(shorts).collect::<Vec<_>>()
        })
        .collect();
    flags.sort();
    flags.dedup();
    let aliases: Vec<&str> = command.get_all_aliases().collect();
    entries.push(serde_json::json!({ "path": path, "flags": flags, "aliases": aliases }));
    for sub in command
        .get_subcommands()
        .filter(|sub| sub.get_name() != "help")
    {
        path.push(sub.get_name().to_owned());
        command_entries(sub, path, entries);
        path.pop();
    }
}

/// The frontmatter and the generated-file comment.
fn frontmatter(title: &str, description: &str) -> String {
    format!(
        "---\ntitle: {}\ndescription: {}\nkind: reference\n---\n\n{GENERATED}",
        yaml(title),
        yaml(&sentence(description))
    )
}

/// `text` trimmed and closed with a period, since clap summaries drop theirs.
fn sentence(text: &str) -> String {
    let text = text.trim();
    if text.is_empty() || text.ends_with(['.', ':', '!', '?']) {
        text.to_owned()
    } else {
        format!("{text}.")
    }
}

/// The long help without its first paragraph when that only repeats `about`,
/// which the page already carries as its description.
fn without_summary(help: &str, about: &str) -> String {
    let help = help.trim();
    let (first, rest) = help.split_once("\n\n").unwrap_or((help, ""));
    let first = first.lines().collect::<Vec<_>>().join(" ");
    if first.trim_end_matches('.') == about.trim().trim_end_matches('.') {
        rest.to_owned()
    } else {
        help.to_owned()
    }
}

/// A YAML scalar: plain when YAML reads it back unchanged, else double-quoted.
fn yaml(value: &str) -> String {
    let plain = !value.contains([':', '#', '"', '\\'])
        && !value.starts_with([
            '-', '?', ',', '[', ']', '{', '}', '&', '*', '!', '|', '>', '\'', '%', '@', '`', ' ',
        ])
        && !value.ends_with(' ');
    if plain {
        value.to_owned()
    } else {
        format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
    }
}

/// One command: its help, usage, options and examples, then its subcommands
/// one heading level deeper. `level` 1 is the page itself, without a heading.
fn section(page: &mut String, command: &Command, parent: &str, level: usize) {
    let path = format!("{parent} {}", command.get_name());
    if level > 1 {
        page.push_str(&format!("{} {path}\n\n", "#".repeat(level)));
    }
    if let Some(help) = command.get_long_about().or(command.get_about()) {
        let mut help = help.to_string();
        if level == 1 {
            let about = command.get_about().map(|about| about.to_string());
            help = without_summary(&help, &about.unwrap_or_default());
        }
        page.push_str(&paragraphs(&help));
    }
    let usage = usage(command);
    page.push_str(&format!("```text\n{usage}\n```\n\n"));
    let mut arguments = command
        .get_arguments()
        .filter(|arg| shown(arg) && !arg.is_global_set())
        .peekable();
    if arguments.peek().is_some() {
        for arg in arguments {
            page.push_str(&argument(arg, &usage));
        }
        page.push('\n');
    }
    if let Some(after) = command.get_after_long_help().or(command.get_after_help()) {
        page.push_str(&format!("```text\n{}\n```\n\n", after.to_string().trim()));
    }
    for sub in visible(command) {
        section(page, sub, &path, level + 1);
    }
}

/// Help text as Markdown paragraphs: the lines of a paragraph joined, and a
/// block with indented or list-like lines kept as it is in a `text` fence,
/// since clap help is hard-wrapped for a terminal and lays out tables with spaces.
fn paragraphs(text: &str) -> String {
    let mut blocks: Vec<(bool, String)> = Vec::new();
    for block in text.trim().split("\n\n") {
        let lines: Vec<&str> = block.lines().collect();
        let prose = lines.iter().take_while(|line| !laid_out(line)).count();
        if prose > 0 {
            let mut text = escape(&lines[..prose].join(" "));
            if blocks.is_empty() {
                text = sentence(&text);
            }
            blocks.push((false, text));
        }
        if prose < lines.len() {
            let fenced = dedent(&lines[prose..]);
            // Blocks of one table or list split by a blank line stay in one fence.
            match blocks.last_mut() {
                Some((true, previous)) if prose == 0 => {
                    previous.push_str("\n\n");
                    previous.push_str(&fenced);
                }
                _ => blocks.push((true, fenced)),
            }
        }
    }
    blocks
        .into_iter()
        .map(|(fenced, text)| {
            if fenced {
                format!("```text\n{text}\n```\n\n")
            } else {
                format!("{text}\n\n")
            }
        })
        .collect()
}

/// Whether a help line is laid out by position (indented, or a list item)
/// rather than wrapped prose.
fn laid_out(line: &str) -> bool {
    let trimmed = line.trim_start();
    let numbered = trimmed.split_once(". ").is_some_and(|(number, _)| {
        !number.is_empty() && number.chars().all(|c| c.is_ascii_digit())
    });
    line.starts_with([' ', '\t'])
        || trimmed.starts_with("- ")
        || trimmed.starts_with("* ")
        || numbered
}

/// The lines without the indent they all share.
fn dedent(lines: &[&str]) -> String {
    let shared = lines
        .iter()
        .filter(|line| !line.trim().is_empty())
        .map(|line| line.len() - line.trim_start().len())
        .min()
        .unwrap_or(0);
    lines
        .iter()
        .map(|line| line.get(shared..).unwrap_or("").trim_end())
        .collect::<Vec<_>>()
        .join("\n")
}

/// Help text with the characters Markdown would read as HTML, emphasis or
/// strikethrough escaped, outside inline code; help such as
/// `DEVLANES_PUBLIC_URL_<SERVICE>` would otherwise lose its placeholder.
fn escape(text: &str) -> String {
    let mut escaped = String::with_capacity(text.len());
    let mut code = false;
    for character in text.chars() {
        if character == '`' {
            code = !code;
        } else if !code && matches!(character, '<' | '*' | '~') {
            escaped.push('\\');
        }
        escaped.push(character);
    }
    escaped
}

/// Hidden commands and options as `(usage, help)`: a hidden subcommand once,
/// without its children, and each hidden option of a visible command.
fn hidden(command: &Command, path: &str, found: &mut Vec<(String, String)>) {
    for arg in command
        .get_arguments()
        .filter(|arg| arg.is_hide_set() && !arg.is_global_set())
        .filter(|arg| !matches!(arg.get_id().as_str(), "help" | "version"))
    {
        if let Some(long) = arg.get_long() {
            let help = arg
                .get_help()
                .map(|help| help.to_string())
                .unwrap_or_default();
            found.push((format!("{path} --{long}"), help));
        }
    }
    for sub in command
        .get_subcommands()
        .filter(|sub| sub.get_name() != "help")
    {
        if sub.is_hide_set() {
            let about = sub
                .get_about()
                .map(|about| about.to_string())
                .unwrap_or_default();
            found.push((usage(sub), about));
        } else {
            hidden(sub, &format!("{path} {}", sub.get_name()), found);
        }
    }
}

/// Subcommands a user can see, without clap's `help`.
fn visible(command: &Command) -> impl Iterator<Item = &Command> {
    command
        .get_subcommands()
        .filter(|sub| !sub.is_hide_set() && sub.get_name() != "help")
}

/// Arguments a user can see, without `--help` and `--version`.
fn shown(arg: &Arg) -> bool {
    !arg.is_hide_set() && !matches!(arg.get_id().as_str(), "help" | "version")
}

/// The usage lines without the `Usage: ` prefix, and without the indent that
/// lines a second usage up under the first in a terminal.
fn usage(command: &Command) -> String {
    let mut command = command.clone();
    let text = command.render_usage().to_string();
    let text = text.trim().strip_prefix("Usage: ").unwrap_or(text.trim());
    text.lines()
        .map(|line| line.strip_prefix("       ").unwrap_or(line))
        // A Windows build names itself `devlanes.exe`; the docs name the command.
        .map(|line| line.replacen("devlanes.exe", "devlanes", 1))
        .collect::<Vec<_>>()
        .join("\n")
}

/// Whether a usage line names `<value>` outside any `[...]` and not right
/// after a flag, as a required positional.
fn required_in(usage: &str, value: &str) -> bool {
    let wanted = format!("<{value}>");
    usage.lines().any(|line| {
        let mut depth = 0_i32;
        let mut after_flag = false;
        line.split_whitespace().any(|word| {
            // `--local <LANE>` is the flag's value, not the positional.
            let found = depth == 0 && !after_flag && word.trim_end_matches("...") == wanted;
            after_flag = word.trim_start_matches('[').starts_with('-');
            depth += i32::try_from(word.matches('[').count()).unwrap_or(0);
            depth -= i32::try_from(word.matches(']').count()).unwrap_or(0);
            found
        })
    })
}

/// A list item: the flag or positional, its help, possible values, default and
/// environment variable. A positional reads as required when the command's
/// `usage` names it so, as for one that is required unless another argument is given.
fn argument(arg: &Arg, usage: &str) -> String {
    let takes_value = arg.get_action().takes_values();
    let mut name = match (arg.get_short(), arg.get_long()) {
        (None, None) => {
            let value = value_name(arg);
            if arg.is_required_set() || required_in(usage, &value) {
                format!("<{value}>")
            } else {
                format!("[{value}]")
            }
        }
        (short, long) => {
            let mut flags = Vec::new();
            if let Some(short) = short {
                flags.push(format!("-{short}"));
            }
            if let Some(long) = long {
                flags.push(format!("--{long}"));
            }
            let mut text = flags.join(", ");
            if takes_value {
                text.push_str(&format!(" <{}>", value_name(arg)));
            }
            text
        }
    };
    if arg
        .get_num_args()
        .is_some_and(|range| range.max_values() > 1)
    {
        name.push_str("...");
    }
    let help = arg
        .get_long_help()
        .or(arg.get_help())
        .map(|help| help.to_string())
        .unwrap_or_default();
    let mut item = format!("- `{name}`: {}", indent(paragraphs(&help).trim()));
    if takes_value {
        let values: Vec<String> = arg
            .get_possible_values()
            .iter()
            .filter(|value| !value.is_hide_set())
            .map(|value| match value.get_help() {
                Some(help) => format!("`{}` ({})", value.get_name(), escape(&help.to_string())),
                None => format!("`{}`", value.get_name()),
            })
            .collect();
        if !values.is_empty() {
            item.push_str(&format!("\n  - Values: {}.", values.join(", ")));
        }
        let defaults: Vec<String> = arg
            .get_default_values()
            .iter()
            .map(|value| format!("`{}`", value.to_string_lossy()))
            .collect();
        if !defaults.is_empty() {
            item.push_str(&format!("\n  - Default: {}.", defaults.join(", ")));
        }
    }
    // A hidden env is one the help text already names.
    if let Some(env) = arg.get_env().filter(|_| !arg.is_hide_env_set()) {
        item.push_str(&format!("\n  - Environment: `{}`.", env.to_string_lossy()));
    }
    item.push('\n');
    item
}

/// The value placeholder: clap's value name, or the argument id in capitals.
fn value_name(arg: &Arg) -> String {
    arg.get_value_names()
        .and_then(|names| names.first())
        .map(|name| name.to_string())
        .unwrap_or_else(|| arg.get_id().as_str().to_uppercase())
}

/// Continuation lines indented under their list item; blank lines kept blank.
fn indent(text: &str) -> String {
    text.lines()
        .map(|line| {
            if line.is_empty() {
                String::new()
            } else {
                format!("  {line}")
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
        .trim_start()
        .to_owned()
}
